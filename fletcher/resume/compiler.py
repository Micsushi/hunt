from __future__ import annotations

import re
import shutil
from pathlib import Path

from .compiler_process import run_tool


def compile_tex(tex_path: str | Path) -> dict:
    tex_path = Path(tex_path)
    output_dir = tex_path.parent
    pdflatex = shutil.which("pdflatex")
    if not pdflatex:
        return {
            "compile_status": "tool_missing",
            "pdf_path": None,
            "page_count": None,
            "fits_one_page": False,
            "log_text": "pdflatex not found on PATH.",
        }

    result = run_tool(
        [pdflatex, "-interaction=nonstopmode", "-halt-on-error", tex_path.name],
        cwd=output_dir,
    )
    pdf_path = output_dir / f"{tex_path.stem}.pdf"
    page_count = None
    successful = (
        not result["failure"]
        and result["returncode"] == 0
        and pdf_path.exists()
        and pdf_path.stat().st_size > 0
    )
    if successful:
        page_count = get_pdf_page_count(pdf_path)

    return {
        "compile_status": "ok" if successful else (result["failure"] or "failed"),
        "pdf_path": str(pdf_path) if successful else None,
        "page_count": page_count,
        "fits_one_page": page_count == 1,
        "log_text": result["output"],
    }


def get_pdf_page_count(pdf_path: str | Path) -> int | None:
    pdfinfo = shutil.which("pdfinfo")
    if pdfinfo:
        result = run_tool([pdfinfo, str(pdf_path)], timeout=10, max_output=65536)
        if not result["failure"] and result["returncode"] == 0:
            for line in result["output"].splitlines():
                if line.startswith("Pages:"):
                    try:
                        pages = int(line.split(":", 1)[1].strip())
                        return pages if pages > 0 else None
                    except ValueError:
                        return None

    # Fallback for environments without pdfinfo. The PDFs generated by our
    # LaTeX flow are simple enough that counting page objects is a useful last
    # resort when external tooling is unavailable.
    with Path(pdf_path).open("rb") as stream:
        data = stream.read(16 * 1024 * 1024 + 1)
    if len(data) > 16 * 1024 * 1024 or b"/ObjStm" in data:
        return None
    page_objects = len(re.findall(rb"/Type\s*/Page\b", data))
    return page_objects or None
