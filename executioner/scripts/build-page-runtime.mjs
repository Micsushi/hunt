// Chrome and Playwright both serialize fillVisibleFields and discard module scope.
// Embed only the declared browser component factories in the shipped function.
import { readFileSync, writeFileSync } from 'node:fs';
import { bambooResumeControl, fillVisibleFields, pageRuntimeComponents } from '../src/browser/page-runtime/fill.js';

const normalize = source => source.replaceAll('\r\n', '\n');
const entry = normalize(fillVisibleFields.toString());
const firstStatement = entry.indexOf('\n');
const embedded = pageRuntimeComponents.map(factory => normalize(factory.toString()).split('\n').map(line => '  ' + line).join('\n')).join('\n');
const output = '// Generated by scripts/build-page-runtime.mjs from src/browser/page-runtime.\n' +
  'export ' + normalize(bambooResumeControl.toString()) + '\n\nexport ' +
  entry.slice(0, firstStatement) + '\n' + embedded + entry.slice(firstStatement) + '\n';
const target = new URL('../extension/generic-fill.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (normalize(readFileSync(target, 'utf8')) !== output) throw new Error('Rebuild extension/generic-fill.js with npm run build:page-runtime');
} else {
  writeFileSync(target, output);
}
